"""Generate walkthrough.py: the whole method in one file, in the order the loop runs, from the real source.

It is a reading artifact, regenerated rather than edited, so it can never drift from the code
(tests/test_walkthrough.py fails if it does). Run: python tools/make_walkthrough.py
"""
import inspect
import os
import sys
import textwrap

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import envs.base, infra.gate, infra.memory, policy.lora, propose, rollout, rsi, update.memory, update.weights, verify  # noqa: E402,E401

SECTIONS = [
    ("The loop. Everything else is called from here.", [rsi.rsi]),
    ("The task contract and the split that keeps held-out honest.", [envs.base.Task, envs.base.split_for_seed]),
    ("Choosing what to practice: the competence frontier.", [propose.frontier_weight, propose.SelfProposer.__call__]),
    ("Acting: one episode.", [rollout.rollout]),
    ("Verifying: ground truth, and the reward-hacking tripwires.", [verify.hack_flags, verify.OutcomeVerifier]),
    ("Carrier A5, weights: GRPO from scratch.", [update.weights.group_advantages, update.weights.grpo_token_loss,
                                                 update.weights.WeightsUpdater.propose]),
    ("...on LoRA adapters, also from scratch.", [policy.lora.LoRALinear]),
    ("Carrier A3, memory: a skill library with exact revert.", [update.memory.MemoryUpdater.propose,
                                                                infra.memory.SkillStore.append]),
    ("The gate: an update is kept only if it clears the bar.", [infra.gate.gate]),
]

HEADER = '''"""nanoVLM-RSI, the whole method in one file — generated by tools/make_walkthrough.py from the real modules.

Read it top to bottom; don't run it (imports are elided). Edit the modules, then regenerate.
"""
'''


def build() -> str:
    parts = [HEADER]
    for i, (title, objs) in enumerate(SECTIONS, 1):
        parts.append(f"\n# {'=' * 96}\n# {i}. {title}\n# {'=' * 96}\n")
        for obj in objs:
            parts.append("\n" + textwrap.dedent(inspect.getsource(obj)))
    return "".join(parts)


if __name__ == "__main__":
    text = build()
    if "--stdout" in sys.argv:
        sys.stdout.write(text)
    else:
        with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "walkthrough.py"), "w") as f:
            f.write(text)
        print(f"wrote walkthrough.py ({text.count(chr(10))} lines)")
